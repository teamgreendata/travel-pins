// Author-time build: generate lib/continents.ts (ISO alpha-2 -> continent) from
// Natural Earth 110m, for the "continents cleared" passport stat (spec §9).
// Keyed by the same cleaned ISO codes (ISO_A2_EH) as the country choropleth. Run:
//   curl -sL -o public/geo/_raw_countries.geojson <ne_110m countries url>
//   node scripts/build-continents.mjs   (then delete the raw file)
import { readFileSync, writeFileSync } from "node:fs";

const gj = JSON.parse(readFileSync("public/geo/_raw_countries.geojson", "utf8"));

const cleanIso = (p) => {
  for (const k of ["ISO_A2_EH", "ISO_A2"]) {
    const v = p[k];
    if (v && v !== "-99" && /^[A-Za-z]{2}$/.test(v)) return v.toUpperCase();
  }
  return null;
};

const continent = {};
const name = {};
for (const f of gj.features) {
  const iso = cleanIso(f.properties);
  if (!iso) continue;
  const cont = f.properties.CONTINENT;
  if (cont && cont !== "Seven seas (open ocean)") continent[iso] = cont;
  const nm = f.properties.NAME || f.properties.ADMIN;
  if (nm) name[iso] = nm;
}
const sortObj = (o) =>
  Object.keys(o)
    .sort()
    .reduce((a, k) => ((a[k] = o[k]), a), {});

const ts = `// AUTO-GENERATED by scripts/build-continents.mjs (Natural Earth 110m). Do not edit.
// ISO 3166-1 alpha-2 country reference data (continent + display name).
export const COUNTRY_CONTINENT: Record<string, string> = ${JSON.stringify(sortObj(continent), null, 2)};

export const COUNTRY_NAME: Record<string, string> = ${JSON.stringify(sortObj(name), null, 2)};
`;
writeFileSync("lib/continents.ts", ts);

console.log("with continent:", Object.keys(continent).length, "| with name:", Object.keys(name).length);
console.log("FR ->", name.FR, "| US ->", name.US, "| JP ->", name.JP);
